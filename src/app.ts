import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import rateLimit from 'express-rate-limit';
import swagger from 'swagger-ui-express';
import { config } from './config.js';
import { db } from './db.js';
import { authenticate, errorHandler } from './core.js';
import { auth } from './auth.js';
import { users } from './users.js';
import { social } from './social.js';
import { messages } from './messages.js';
import { moderation } from './moderation.js';
import { openapi } from './openapi.js';

export const app = express();
app.disable('x-powered-by');
app.set('json replacer', (_key: string, value: unknown) => typeof value === 'bigint' ? value.toString() : value);
app.use(helmet());
app.use(cors({ origin: config.CORS_ORIGINS.split(',').map(v => v.trim()).filter(Boolean) }));
app.use(express.json({ limit: '64kb' }));
app.get('/health', async (_req, res) => { await db.$queryRaw`SELECT 1`; res.json({ status: 'ok' }); });
app.get('/api/openapi.json', (_req, res) => { res.json(openapi); });
app.use('/api/docs', swagger.serve, swagger.setup(openapi));
app.use('/api/v1', rateLimit({ windowMs: 60000, limit: config.NODE_ENV === 'test' ? 10000 : 300, standardHeaders: 'draft-8', legacyHeaders: false, message: { error: 'Demasiadas solicitudes; inténtalo más tarde' } }));
app.use('/api/v1/auth', rateLimit({ windowMs: 900000, limit: config.NODE_ENV === 'test' ? 10000 : 30, standardHeaders: 'draft-8', legacyHeaders: false, message: { error: 'Demasiados intentos de autenticación' } }), auth);
app.use('/api/v1', authenticate, users, social, messages, moderation);
app.use((_req, res) => { res.status(404).json({ error: 'Ruta no encontrada' }); });
app.use(errorHandler);
